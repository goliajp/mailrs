//! Bitwarden's SimpleLogin and addy.io forwarders, pointed at this server,
//! make masked addresses. Each request is the one Bitwarden sends, as
//! written in bitwarden/clients at 2444eee6958f
//! (`libs/tools/generator/core/src/integration/simple-login.ts` and
//! `addy-io.ts`, the note text from `generatedBy` in
//! `libs/common/src/tools/integration/integration-context.ts` with the
//! English messages):
//!
//! - SimpleLogin: `POST {baseUrl}/api/alias/random/new`, with
//!   `?hostname=<host>` when the site is known, the key bare in an
//!   `Authentication` header, body `{"note": …}`; 200 or 201 is success and
//!   the address is read from `alias`.
//! - addy.io: `POST {baseUrl}/api/v1/aliases`, `Authorization: Bearer
//!   <key>`, body `{"domain", "description"}`; 200 or 201 is success and
//!   the address is read from `data.email`.
//!
//! Also: only a key scoped to masked addresses is taken, an addy.io domain
//! the account may not use is a validation error, every mask made is in
//! the audit log, and an administrator reads the masks' submission log.

mod live;

use mailrs_core_sidestate::families::audit::AuditFact;
use mailrs_core_sidestate::families::masked_email::submit_log;
use mailrs_core_sidestate::keys::admin::AUDIT_LOG;
use reqwest::Method;
use serde_json::{Value, json};

const OWNER: &str = "owner@example.test";
const ADMIN: &str = "admin@example.test";

async fn key(live: &live::Live, session: &str, scopes: Value) -> String {
    let (status, key) = live
        .call(
            Method::POST,
            "/api/agent/keys",
            session,
            Some(json!({ "name": "password manager", "scopes": scopes })),
        )
        .await;
    assert_eq!(status, 200, "{key}");
    key["secret"].as_str().expect("secret").to_string()
}

/// SimpleLogin's request; (status, body).
async fn simplelogin(live: &live::Live, auth: &str, host: Option<&str>) -> (u16, Value) {
    let (url, note) = match host {
        Some(h) => (
            format!("{}/api/alias/random/new?hostname={h}", live.base),
            format!("Website: {h}. Generated by Bitwarden."),
        ),
        None => (
            format!("{}/api/alias/random/new", live.base),
            "Generated by Bitwarden.".to_string(),
        ),
    };
    let res = live
        .http
        .post(url)
        .header("Authentication", auth)
        .json(&json!({ "note": note }))
        .send()
        .await
        .expect("request");
    let status = res.status().as_u16();
    (status, res.json().await.unwrap_or(Value::Null))
}

/// addy.io's request; (status, body).
async fn addy(live: &live::Live, key: &str, domain: &str) -> (u16, Value) {
    live.call(
        Method::POST,
        "/api/v1/aliases",
        key,
        Some(json!({ "domain": domain, "description": "Website: shop.example. Generated by Bitwarden." })),
    )
    .await
}

fn audited(kevy: &str, action: &str, target: &str) -> bool {
    let mut c = kevy_client::Connection::connect(kevy).expect("kevy");
    c.lrange(AUDIT_LOG, 0, -1)
        .expect("audit")
        .iter()
        .filter_map(|r| serde_json::from_slice::<AuditFact>(r).ok())
        .any(|f| f.actor == OWNER && f.action == action && f.target == target)
}

async fn assert_made(live: &live::Live, kevy: &str, email: &str) {
    assert!(email.ends_with("@example.test"), "{email}");
    assert!(live.core.recipient_deliverable(email).await.expect("check"));
    let prefix: String = email.chars().take(8).collect();
    assert!(audited(kevy, "mask.create", &prefix), "audited");
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn password_manager_forwarders_make_masks() {
    let (_kevy, kevy) = mailrs_test_docker::kevy::kevy_server().await;
    let tmp = tempfile::tempdir().expect("tmp");
    // SAFETY: the only test in this binary, before anything reads them
    unsafe {
        std::env::set_var("MAILRS_KEVY_URL", &kevy);
        std::env::set_var("MAILRS_MAILDIR", tmp.path());
    }
    let live = live::start(&kevy).await;
    live.add_account(OWNER, "pw").await;
    let session = live.login(OWNER, "pw").await;
    // making a key asks for a recent password confirmation
    live.confirm(&session, "pw").await;
    let masked = key(&live, &session, json!(["masked_email"])).await;
    let reader = key(&live, &session, json!(["mail:read"])).await;

    // SimpleLogin, with the site and without
    let (status, made) = simplelogin(&live, &masked, Some("accounts.example.org")).await;
    assert_eq!(status, 201, "{made}");
    let email = made["alias"].as_str().expect("alias").to_string();
    assert_made(&live, &kevy, &email).await;
    let (_, list) = live
        .call(Method::GET, "/api/masked-emails", &session, None)
        .await;
    let row = list
        .as_array()
        .expect("list")
        .iter()
        .find(|m| m["email"] == email.as_str())
        .expect("listed");
    assert_eq!(row["forDomain"], "accounts.example.org");
    assert_eq!(
        row["description"],
        "Website: accounts.example.org. Generated by Bitwarden."
    );
    let (status, made) = simplelogin(&live, &masked, None).await;
    assert_eq!(status, 201, "{made}");
    assert_made(&live, &kevy, made["alias"].as_str().expect("alias")).await;

    // only a mask key: not another key, not a session, in either header
    let (status, _) = simplelogin(&live, &reader, None).await;
    assert_eq!(status, 403, "a key without the scope");
    let (status, _) = simplelogin(&live, &session, None).await;
    assert_eq!(
        status, 401,
        "a session token is not read from Authentication"
    );
    let (status, _) = live
        .call(
            Method::POST,
            "/api/alias/random/new",
            &session,
            Some(json!({})),
        )
        .await;
    assert_eq!(status, 403, "a session in Authorization");

    // addy.io, on the account's own domain and on one it may not use
    let (status, made) = addy(&live, &masked, "example.test").await;
    assert_eq!(status, 201, "{made}");
    assert_made(&live, &kevy, made["data"]["email"].as_str().expect("email")).await;
    let (status, refused) = addy(&live, &masked, "elsewhere.example").await;
    assert_eq!(status, 422, "{refused}");
    assert!(refused["errors"]["domain"].is_array(), "{refused}");
    let (status, _) = addy(&live, &reader, "example.test").await;
    assert_eq!(status, 403);

    // the masks' submission log, for a super administrator only
    {
        let mut c = kevy_client::Connection::connect(&kevy).expect("kevy");
        let row = submit_log::Submission {
            at: 1_700_000_000,
            account: OWNER.into(),
            mask: "amber.ot".into(),
            ip: "203.0.113.9".into(),
        };
        submit_log::append(&mut c, &row).expect("append");
    }
    let (status, _) = live
        .call(Method::GET, "/api/admin/masked-submissions", &session, None)
        .await;
    assert_eq!(status, 403, "an ordinary account");
    live.add_account(ADMIN, "pw").await;
    live.make_super(ADMIN);
    let admin = live.login(ADMIN, "pw").await;
    let (status, rows) = live
        .call(Method::GET, "/api/admin/masked-submissions", &admin, None)
        .await;
    assert_eq!(status, 200, "{rows}");
    assert_eq!(rows[0]["ip"], "203.0.113.9", "{rows}");
    assert_eq!(rows[0]["account"], OWNER);
}
