//! Request fixtures for masked addresses and the password-manager
//! forwarders: the same contract as `request_contract.rs`, whose
//! `every_fixture_has_a_test` lists these fixtures too.

mod common;
use common::parse;
use mailrs_webapi::handlers;

#[test]
fn masked_email_bodies_match() {
    let v: handlers::masked_email::CreateBody = parse("masked-email-create");
    assert_eq!(v.for_domain, "shop.example");
    assert_eq!(v.description, "orders");
    assert_eq!(v.domain, None);
    let v: handlers::masked_email::UpdateBody = parse("masked-email-update");
    assert_eq!(v.state.as_deref(), Some("disabled"));
    assert_eq!(v.url, None, "absent url is no change");
}

#[test]
fn bitwarden_forwarder_bodies_match() {
    let v: handlers::forwarders::SimpleLoginBody = parse("simplelogin-alias-new");
    assert_eq!(
        v.note,
        "Website: accounts.example.org. Generated by Bitwarden."
    );
    let v: handlers::forwarders::AddyBody = parse("addy-alias-create");
    assert_eq!(v.domain, "example.test");
    assert_eq!(
        v.description,
        "Website: shop.example. Generated by Bitwarden."
    );
}
