#!/usr/bin/env bash
# Regenerate the Japanese bank name list the fraud facts check a written
# bank name against (crates/fraud/data/jp-bank-names.tsv) and its notice.
#
# Run by hand, on a workstation with network access, when the regulator's
# lists change (they are updated every few weeks; quarterly is enough).
# Needs only curl and python3 (standard library: the .xlsx files are read
# as the zip of XML they are, no spreadsheet package).
#
# Prints what changed against the committed list — added, removed, and
# renamed (same corporate number, new name) — for the commit message.
set -euo pipefail
cd "$(dirname "$0")/.."

BASE='https://www.fsa.go.jp/menkyo/menkyoj'
SHEETS='ginkou shinkin shinkumi rokin'
DATA=crates/fraud/data
TSV="$DATA/jp-bank-names.tsv"
NOTICE="$DATA/jp-bank-names.NOTICE"
TODAY=$(date +%Y-%m-%d)

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
for s in $SHEETS; do
  curl -fsSL -m 60 -o "$work/$s.xlsx" "$BASE/$s.xlsx"
done

python3 -I - "$work" "$TSV" "$TODAY" > "$work/new.tsv" <<'PY'
import re, sys, zipfile
import xml.etree.ElementTree as ET

work, _, today = sys.argv[1:4]
M = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
NS = {"m": M}
REL = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"
KINDS = {"ginkou": "銀行", "shinkin": "信用金庫", "shinkumi": "信用組合", "rokin": "労働金庫"}


def sheets(path):
    z = zipfile.ZipFile(path)
    shared = []
    if "xl/sharedStrings.xml" in z.namelist():
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS):
            # the text and its rich-text runs; the reading guides (rPh) left out
            parts = [t.text or "" for t in si.findall("m:t", NS)]
            parts += [t.text or "" for t in si.findall("m:r/m:t", NS)]
            shared.append("".join(parts))
    wb = ET.fromstring(z.read("xl/workbook.xml"))
    rels = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
    target = {r.get("Id"): r.get("Target") for r in rels}
    for sheet in wb.find("m:sheets", NS):
        t = target[sheet.get(REL)].lstrip("/")
        t = t if t.startswith("xl/") else "xl/" + t
        rows = []
        for row in ET.fromstring(z.read(t)).iter("{%s}row" % M):
            cells = {}
            for c in row.findall("m:c", NS):
                col = re.match(r"[A-Z]+", c.get("r")).group(0)
                v = c.find("m:v", NS)
                if c.get("t") == "s" and v is not None:
                    cells[col] = shared[int(v.text)]
                elif c.get("t") == "inlineStr":
                    cells[col] = "".join(x.text or "" for x in c.iter("{%s}t" % M))
                elif v is not None:
                    cells[col] = v.text or ""
            rows.append(cells)
        yield sheet.get("name"), rows


out = []
for stem, kind in KINDS.items():
    for sheet, rows in sheets(f"{work}/{stem}.xlsx"):
        header = next(
            (i for i, r in enumerate(rows) if any(v.strip() in ("銀行名", "名称") for v in r.values())),
            None,
        )
        if header is None:
            sys.exit(f"{stem}.xlsx / {sheet}: no 銀行名 or 名称 column; the layout changed")
        cols = {v.strip(): k for k, v in rows[header].items()}
        name_col = cols.get("銀行名") or cols["名称"]
        corp_col = cols["法人番号"]
        sheet_kind = "外国銀行支店" if sheet == "外国銀行支店" else kind
        for r in rows[header + 1:]:
            name = re.sub(r"\s+", "", r.get(name_col, ""))
            if not name or name.startswith(("（注", "(注", "※")):
                continue
            corp = re.sub(r"\D", "", r.get(corp_col, ""))
            # a few rows carry a postcode in this column; only a
            # thirteen-digit number is a corporate number
            corp = corp if len(corp) == 13 else ""
            out.append((sheet_kind, name, corp))

print("# Japanese bank names: kind<TAB>name<TAB>corporate number.")
print(f"# Snapshot {today}; see jp-bank-names.NOTICE. Regenerated by scripts/update-jp-bank-names.sh.")
for kind, name, corp in out:
    print(f"{kind}\t{name}\t{corp}")
PY

python3 -I - "$TSV" "$work/new.tsv" <<'PY'
import collections, os, sys

def read(path):
    rows = []
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            if line.startswith("#") or not line.strip():
                continue
            kind, name, corp = (line.rstrip("\n").split("\t") + ["", ""])[:3]
            rows.append((kind, name, corp))
    return rows

old, new = read(sys.argv[1]), read(sys.argv[2])
by_corp_old = {c: n for _, n, c in old if c}
by_corp_new = {c: n for _, n, c in new if c}
old_names = {n for _, n, _ in old}
new_names = {n for _, n, _ in new}
renamed = sorted(
    (by_corp_old[c], by_corp_new[c])
    for c in by_corp_old.keys() & by_corp_new.keys()
    if by_corp_old[c] != by_corp_new[c]
)
moved = {a for a, _ in renamed} | {b for _, b in renamed}
added = sorted(new_names - old_names - moved)
removed = sorted(old_names - new_names - moved)
counts = collections.Counter(k for k, _, _ in new)
print("rows by kind: " + ", ".join(f"{k} {v}" for k, v in counts.items()) + f" (total {len(new)})")
print(f"added ({len(added)}): " + "、".join(added))
print(f"removed ({len(removed)}): " + "、".join(removed))
print(f"renamed ({len(renamed)}): " + "、".join(f"{a} → {b}" for a, b in renamed))
PY

mkdir -p "$DATA"
mv "$work/new.tsv" "$TSV"
cat > "$NOTICE" <<EOF
jp-bank-names.tsv is made from the following lists of the Financial
Services Agency of Japan (金融庁), downloaded on $TODAY. Only the names,
the kind of institution and the corporate number are kept.

出典：金融庁ウェブサイト「免許・許可・登録等を受けている業者一覧」
https://www.fsa.go.jp/menkyo/menkyo.html （$TODAY に利用）
EOF
for s in $SHEETS; do
  echo "  $BASE/$s.xlsx" >> "$NOTICE"
done
cat >> "$NOTICE" <<EOF
を加工して作成

Licence: 公共データ利用規約（第1.0版）(PDL1.0), compatible with CC BY 4.0.
https://www.digital.go.jp/resources/open_data/public_data_license_v1.0
EOF
